// Generate plugin/src/test/resources/duel-vectors.json from the browser rules.
//
// The plugin is a Java port of duels/js/duels.js. These vectors pin the two
// together: a scripted duel full of edge cases, run through the JS rules, with
// every accept/refuse decision and the final state recorded. The plugin's tests
// replay the same messages and must agree on all of it.
//
//   node --no-warnings test/duel-vectors.mjs

import { writeFileSync } from 'node:fs';
import { blake2b } from '../shared/blake2b.js';
import { createCommander } from '../shared/accounts.js';
import { ACCOUNTS } from '../shared/config.js';
import { toHex, utf8 } from '../shared/crypto.js';
import { CONFIG as BASE } from '../duels/js/config.js';
import { Duel, Lobby, duelTopic, lobbyOf, lobbyTopic, sealHash, statement } from '../duels/js/duels.js';

const CONFIG = { ...BASE, movesChain: 'duels-chain', keyBinding: 'first-seen' };
const commanders = {};
for (const id of ['satya', 'nova', 'mallory']) {
  commanders[id] = (await createCommander(ACCOUNTS, id, 'correct horse battery', 1000)).commander;
}
const SECRET = { satya: '11'.repeat(16), nova: '22'.repeat(16) };

const entries = [];
let height = 100;
let t = 1_900_000_000_000;
let nonce = 0;
const push = (topic, body) => {
  height += 1;
  t += 1000;
  const messageId = toHex(blake2b(utf8(`vector-${height}`), 32));
  entries.push({ topic, height, index: 0, timestamp: t, messageId, bodyHex: toHex(utf8(JSON.stringify(body))) });
  return messageId;
};
const lobby = (kind, id, field, signer = id) => {
  const n = ++nonce;
  const extra = kind === 'challenge' ? { rounds: field } : { challenge: field };
  return commanders[signer].sign(statement(CONFIG, 'lobby', kind, id, n, field))
    .then((sig) => push(lobbyTopic(CONFIG, lobbyOf(CONFIG, t + 1000)), { t: kind, id, pub: commanders[signer].pub, n, ...extra, sig }));
};
let duelId;
const move = async (kind, id, round, fields, signer = id) => {
  const sig = await commanders[signer].sign(statement(CONFIG, duelId, kind, id, round, ...fields));
  const body = { t: kind, id, round, sig };
  if (kind === 'seal') body.hash = fields[0];
  if (kind === 'reveal') { body.move = fields[0]; body.secret = fields[1]; }
  return push(duelTopic(CONFIG, duelId), body);
};
const seal = (id, round, m, secret = SECRET[id]) => move('seal', id, round, [sealHash(CONFIG, duelId, round, id, m, secret)]);
const reveal = (id, round, m, secret = SECRET[id]) => move('reveal', id, round, [m, secret]);

// --- the script
duelId = await lobby('challenge', 'satya', 5);
await lobby('challenge', 'satya', 7, 'mallory'); // satya's call sign with mallory's own key: refused
await seal('nova', 1, 'laser'); // before the duel exists: refused
await lobby('accept', 'satya', duelId); // your own challenge: refused
await lobby('accept', 'nova', duelId);
await reveal('satya', 1, 'laser'); // nothing to reveal yet
await seal('satya', 1, 'laser');
await move('seal', 'nova', 1, [sealHash(CONFIG, duelId, 1, 'nova', 'recharge', SECRET.nova)], 'mallory'); // forged
await seal('nova', 1, 'recharge');
await reveal('satya', 1, 'laser');
await reveal('nova', 1, 'recharge'); // round 1 settles
await seal('satya', 2, 'shield');
await seal('nova', 2, 'missile');
await reveal('nova', 2, 'missile');
await reveal('satya', 2, 'emp'); // does not match the seal: refused
await reveal('satya', 2, 'shield'); // round 2 settles
await seal('nova', 3, 'laser');
t += CONFIG.sealMs + 2000; // satya never seals round 3
await move('forfeit', 'nova', 3, []); // round 3 settles at its deadline
await seal('satya', 4, 'missile'); // 1 energy left after the shield: a missile costs 2
await seal('nova', 4, 'emp');
await reveal('satya', 4, 'missile');
await reveal('nova', 4, 'emp'); // round 4: the unaffordable missile counts as a forfeit
await seal('satya', 5, 'missile'); // still unaffordable
await seal('nova', 5, 'laser');
await reveal('nova', 5, 'laser');
await reveal('satya', 5, 'missile'); // unaffordable: a forfeit; the duel ends
await seal('satya', 6, 'laser'); // after the end: refused

// --- run the browser rules
const lob = new Lobby(CONFIG);
let duel = null;
const outcomes = [];
for (const e of entries) {
  if (e.topic.includes('.lobby.')) {
    const r = await lob.apply(e, async () => ({ ok: true }));
    outcomes.push({ accepted: r.accepted, reason: r.reason ?? null });
    if (r.accepted && r.kind === 'accept') duel = new Duel(CONFIG, r.duelId, lob.challenges.get(r.duelId));
  } else if (!duel) {
    outcomes.push({ accepted: false, reason: 'no such duel yet' });
  } else {
    const r = await duel.apply(e);
    outcomes.push({ accepted: r.accepted, reason: r.reason ?? null });
  }
}

const vectors = {
  note: 'Generated by test/duel-vectors.mjs from duels/js/duels.js. Do not edit by hand.',
  chainId: CONFIG.movesChain,
  duelId,
  entries: entries.map((e, i) => ({ ...e, expected: outcomes[i] })),
  final: {
    hp: duel.hp, energy: duel.energy, round: duel.round, phase: duel.phase, winner: duel.winner,
    history: duel.history.map((h) => ({ round: h.round, moves: h.moves, forfeited: h.forfeited, die: h.die, dealt: h.dealt })),
  },
};
const out = new URL('../plugin/src/test/resources/duel-vectors.json', import.meta.url);
writeFileSync(out, `${JSON.stringify(vectors, null, 2)}\n`);
console.log(`wrote ${entries.length} entries: ${outcomes.filter((o) => o.accepted).length} accepted, `
  + `${outcomes.filter((o) => !o.accepted).length} refused; winner seat ${duel.winner}, hp ${duel.hp}`);
